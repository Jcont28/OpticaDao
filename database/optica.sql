CREATE DATABASE OpticaDB;
GO
USE OpticaDB;
GO
CREATE TABLE Usuarios(
 UsuarioID INT IDENTITY PRIMARY KEY, Usuario NVARCHAR(120) NOT NULL UNIQUE,
 PasswordHash NVARCHAR(100) NOT NULL, Rol NVARCHAR(20) NOT NULL CHECK(Rol IN ('CLIENTE','VENDEDOR')),
 Activo BIT NOT NULL DEFAULT 1
);
CREATE TABLE Clientes(
 ClienteID INT IDENTITY PRIMARY KEY, UsuarioID INT NOT NULL UNIQUE REFERENCES Usuarios(UsuarioID),
 Nombre NVARCHAR(120) NOT NULL, DNI NVARCHAR(30) NOT NULL UNIQUE,
 Telefono NVARCHAR(30), Correo NVARCHAR(120) NOT NULL UNIQUE
);
CREATE TABLE Vendedores(
 VendedorID INT IDENTITY PRIMARY KEY, UsuarioID INT NOT NULL UNIQUE REFERENCES Usuarios(UsuarioID),
 Nombre NVARCHAR(120) NOT NULL
);
CREATE TABLE Mediciones(
 MedicionID INT IDENTITY PRIMARY KEY, ClienteID INT NOT NULL REFERENCES Clientes(ClienteID),
 Fecha DATE NOT NULL DEFAULT GETDATE(), Ojo NVARCHAR(10) NOT NULL,
 Esfera DECIMAL(6,2) NOT NULL, Cilindro DECIMAL(6,2) NOT NULL DEFAULT 0,
 Eje INT NOT NULL DEFAULT 0, Adicion DECIMAL(6,2) NOT NULL DEFAULT 0, Observaciones NVARCHAR(300)
);
CREATE TABLE Productos(
 ProductoID INT IDENTITY PRIMARY KEY, Nombre NVARCHAR(120) NOT NULL,
 Tipo NVARCHAR(20) NOT NULL CHECK(Tipo IN ('ARO','LUNA','ACCESORIO')),
 Marca NVARCHAR(80), Material NVARCHAR(80), Forma NVARCHAR(80),
 Precio DECIMAL(10,2) NOT NULL CHECK(Precio>=0), Stock INT NOT NULL CHECK(Stock>=0),
 Activo BIT NOT NULL DEFAULT 1
);
CREATE TABLE Apartados(
 ApartadoID INT IDENTITY PRIMARY KEY, ClienteID INT NOT NULL REFERENCES Clientes(ClienteID),
 AroID INT NOT NULL REFERENCES Productos(ProductoID), Fecha DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 Estado NVARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
);
CREATE TABLE Ventas(
 VentaID INT IDENTITY PRIMARY KEY, ClienteID INT NOT NULL REFERENCES Clientes(ClienteID),
 MedicionID INT NOT NULL REFERENCES Mediciones(MedicionID),
 AroID INT NOT NULL REFERENCES Productos(ProductoID), LunaID INT NOT NULL REFERENCES Productos(ProductoID),
 VendedorID INT NOT NULL REFERENCES Vendedores(VendedorID),
 Cantidad INT NOT NULL CHECK(Cantidad>0), Subtotal DECIMAL(12,2) NOT NULL,
 Impuesto DECIMAL(12,2) NOT NULL, Total DECIMAL(12,2) NOT NULL,
 Fecha DATETIME2 NOT NULL DEFAULT SYSDATETIME(), Estado NVARCHAR(20) NOT NULL DEFAULT 'COMPLETADA'
);
